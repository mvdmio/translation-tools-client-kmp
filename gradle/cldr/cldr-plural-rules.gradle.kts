import groovy.json.JsonSlurper

// Compiles the CLDR cardinal plural rules in gradle/cldr/plurals.json down to whole-number rules.
// For a whole number the operands v, w, f, t, c and e are 0 and i equals n, so every relation on
// those operands is a constant and every relation on n or i tests an unsigned magnitude `n`.

val cldrPluralsFile = layout.projectDirectory.file("gradle/cldr/plurals.json")
val cldrPluralRulesFile = layout.projectDirectory.file(
   "src/commonMain/kotlin/io/mvdm/translationtools/client/placeholders/CldrPluralRules.kt"
)

val cldrRuleCategories = listOf("zero", "one", "two", "few", "many")
val cldrRelationPattern = Regex("""([nivwftce])(?: % (\d+))? (!?=) (.+)""")

// One CLDR relation such as `n % 100 = 3..10` as Kotlin source, or the constant "true" / "false".
fun compileCldrRelation(relation: String): String
{
   val (operand, modulo, operator, rangeList) = checkNotNull(cldrRelationPattern.matchEntire(relation.trim())) {
      "Unsupported CLDR plural relation: '$relation'"
   }.destructured
   val negated = operator == "!="
   val ranges = rangeList.split(',').map { item ->
      val bounds = item.trim().split("..").map { it.toLong() }
      bounds.first()..bounds.last()
   }

   if (operand != "n" && operand != "i")
      return (ranges.any { 0L in it } != negated).toString()

   val subject = if (modulo.isEmpty()) "n" else "n % ${modulo}UL"
   val matches = ranges.map { if (it.first == it.last) "$subject == ${it.first}UL" else "$subject in ${it.first}UL..${it.last}UL" }

   return when {
      ranges.size > 1 -> (if (negated) "!(" else "(") + matches.joinToString(" || ") + ")"
      negated -> matches.single().replace(" == ", " != ").replace(" in ", " !in ")
      else -> matches.single()
   }
}

// The `when` condition of one category, or null when no whole number can match it.
fun compileCldrCategory(ruleText: String): String?
{
   val andClauses = ruleText.substringBefore('@').trim().split(" or ").mapNotNull { clause ->
      val relations = clause.split(" and ").map { compileCldrRelation(it) }
      if ("false" in relations) null else relations.filter { it != "true" }
   }

   return when {
      andClauses.isEmpty() -> null
      andClauses.any { it.isEmpty() } -> "true"
      andClauses.size == 1 && andClauses.single().size == 1 -> andClauses.single().single().removeSurrounding("(", ")")
      else -> andClauses.joinToString("\n      || ") { it.joinToString(" && ") }
   }
}

// The body of one language's rule function; a category with an empty rule text is `other`.
fun compileCldrLanguage(categories: Map<*, *>): String
{
   val branches = cldrRuleCategories.mapNotNull { category ->
      val ruleText = categories["pluralRule-count-$category"] as String? ?: return@mapNotNull null
      compileCldrCategory(ruleText)?.let { condition -> "   $condition -> PluralCategory.${category.uppercase()}" }
   }

   return (branches + "   else -> PluralCategory.OTHER").joinToString("\n")
}

fun generateCldrPluralRulesSource(plurals: File): String
{
   val supplemental = (JsonSlurper().parse(plurals) as Map<*, *>)["supplemental"] as Map<*, *>
   val cldrVersion = (supplemental["version"] as Map<*, *>)["_cldrVersion"]
   val languages = (supplemental["plurals-type-cardinal"] as Map<*, *>)
      .map { (tag, categories) -> (tag as String).lowercase().replace('_', '-') to compileCldrLanguage(categories as Map<*, *>) }
      .sortedBy { it.first }

   val tagsByBody = languages.groupBy({ it.second }, { it.first })
   val bodies = tagsByBody.keys.toList()

   val source = StringBuilder()
   source.append(
      """
      // <auto-generated>
      // Generated from CLDR $cldrVersion (gradle/cldr/plurals.json) by the `generateCldrPluralRules` Gradle task.
      // Do not edit by hand: change gradle/cldr/plurals.json or gradle/cldr/cldr-plural-rules.gradle.kts and
      // run `./gradlew generateCldrPluralRules`.
      // </auto-generated>
      @file:Suppress("UNUSED_PARAMETER")

      package io.mvdm.translationtools.client.placeholders

      /** The CLDR cardinal rule for a lowercase, `-`-separated Locale tag, or null when CLDR has none. The argument is the absolute value. */
      internal fun cldrPluralRule(tag: String): ((ULong) -> PluralCategory)? = when (tag)
      {

      """.trimIndent()
   )
   bodies.forEachIndexed { index, body ->
      val tags = tagsByBody.getValue(body).map { "\"$it\"" }
      val lines = tags.chunked(8).joinToString(",\n      ") { it.joinToString(", ") }
      source.append("   $lines -> ::rule$index\n")
   }
   source.append("   else -> null\n}\n")
   bodies.forEachIndexed { index, body ->
      source.append("\nprivate fun rule$index(n: ULong): PluralCategory = when {\n$body\n}\n")
   }

   return source.toString()
}

tasks.register("generateCldrPluralRules") {
   group = "build setup"
   description = "Regenerates CldrPluralRules.kt from the committed CLDR plurals.json. The only way the table changes."

   val input = cldrPluralsFile
   val output = cldrPluralRulesFile
   inputs.file(input)
   outputs.file(output)

   doLast {
      output.asFile.writeText(generateCldrPluralRulesSource(input.asFile))
   }
}

val verifyCldrPluralRules = tasks.register("verifyCldrPluralRules") {
   group = "verification"
   description = "Fails when CldrPluralRules.kt differs from what generateCldrPluralRules would write, i.e. when it was edited by hand."

   val input = cldrPluralsFile
   val committed = cldrPluralRulesFile
   inputs.file(input)
   inputs.file(committed)

   doLast {
      // Compare line endings-agnostic: a Windows checkout with core.autocrlf rewrites the committed file to CRLF.
      check(committed.asFile.readText().replace("\r\n", "\n") == generateCldrPluralRulesSource(input.asFile)) {
         "${committed.asFile.name} is not what generateCldrPluralRules writes from plurals.json. Do not edit it by hand: run `./gradlew generateCldrPluralRules`."
      }
   }
}

tasks.matching { it.name == "check" }.configureEach { dependsOn(verifyCldrPluralRules) }
